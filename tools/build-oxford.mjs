// DSH serves one classic client.js per bundle. Keep the view, theme CSS and
// desktop/web navigation separately editable and deterministically assemble it.
import { readFileSync,writeFileSync } from 'node:fs'
const dir=new URL('../oxford/',import.meta.url)
const read=file=>readFileSync(new URL(file,dir),'utf8').replaceAll('\r\n','\n')
const output=`// Generated by tools/build-oxford.mjs
window.__ModuleLoader__.load({
  id: '@local/dsh-oxford',
  factory(require) {
    const React=require('react')
${read('menu.js')}
${read('workbench.js')}
    return {inject:['slots','layout','locale'],apply(ctx) {
      ctx.effect(()=>{const style=document.createElement('style');style.textContent=${JSON.stringify(read('workbench.css'))};document.head.append(style);return ()=>style.remove()},'oxford: workspace styles')
      ctx.effect(()=>{
        // Also follow the native window while the operator is in another DSH panel.
        const sync=()=>{const theme=document.documentElement.getAttribute('data-arknights-theme');if(['day','night','glass','xlab'].includes(theme))fetch('oxford/theme',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({theme})}).catch(()=>{})}
        const watch=new MutationObserver(sync);watch.observe(document.documentElement,{attributes:true,attributeFilter:['data-arknights-theme']});sync();return ()=>watch.disconnect()
      },'oxford: native palette')
      installOxfordMenu(ctx,React,createOxfordWorkbench(React))
    }}
  }
})
`
if(process.argv.includes('--check')){if(read('client.js')!==output)throw Error('Oxford client out of date: node tools/build-oxford.mjs')}
else writeFileSync(new URL('client.js',dir),output)
